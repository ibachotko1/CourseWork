using System;

namespace SmartGreenhouse.Core.Models
{
    /// <summary>
    /// Данные с датчиков теплицы
    /// Этот класс представляет собой снимок всех показаний датчиков в определенный момент времени.
    /// Используется для мониторинга состояния теплицы и принятия решений о включении/выключении систем.
    /// </summary>
    public class SensorData
    {
        /// <summary>
        /// Температура воздуха в теплице (°C)
        /// Нормальный диапазон: 15-25°C
        /// - Ниже 15°C: требуется включение обогрева
        /// - Выше 25°C: требуется включение вентиляции
        /// </summary>
        public double Temperature { get; set; }        // °C
        
        /// <summary>
        /// Влажность воздуха в теплице (%)
        /// Нормальный диапазон: 50-70%
        /// Измеряется в процентах относительной влажности
        /// </summary>
        public double Humidity { get; set; }           // %
        
        /// <summary>
        /// Влажность почвы в теплице (%)
        /// Нормальный диапазон: 60-70%
        /// - Ниже 60%: требуется включение полива
        /// - Выше 70%: полив следует остановить
        /// </summary>
        public double SoilMoisture { get; set; }       // %
        
        /// <summary>
        /// Уровень углекислого газа (CO₂) в теплице (ppm - parts per million)
        /// Нормальный диапазон: 1000-1200 ppm
        /// - Выше 1200 ppm: требуется включение вентиляции для проветривания
        /// </summary>
        public double CO2Level { get; set; }           // ppm
        
        /// <summary>
        /// Интенсивность освещения в теплице (lux - люксы)
        /// Нормальный диапазон: 3000-5000 lux
        /// - Ниже 3000 lux: может потребоваться включение искусственного освещения
        /// </summary>
        public double LightIntensity { get; set; }     // lux
        
        /// <summary>
        /// Временная метка снятия показаний датчиков
        /// Используется для ведения истории измерений и построения графиков
        /// </summary>
        public DateTime Timestamp { get; set; }
    }
}
