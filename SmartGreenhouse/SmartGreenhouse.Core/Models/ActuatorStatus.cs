namespace SmartGreenhouse.Core.Models
{
    /// <summary>
    /// Статус исполнительных механизмов теплицы
    /// 
    /// Этот класс представляет собой набор булевых переменных (true/false),
    /// описывающих состояние (включено/выключено) всех исполнительных устройств.
    /// 
    /// ЛР4: Эти булевы состояния используются в булевых функциях для принятия
    /// логических решений о том, какие системы должны быть активны.
    /// </summary>
    public class ActuatorStatus
    {
        /// <summary>
        /// Клапан полива воды
        /// - true: клапан открыт, вода подается в теплицу
        /// - false: клапан закрыт, полив не производится
        /// Управляется на основе показаний датчика влажности почвы
        /// </summary>
        public bool WaterValve { get; set; }      // Клапан полива
        
        /// <summary>
        /// Обогреватель теплицы
        /// - true: обогреватель включен, температура повышается
        /// - false: обогреватель выключен
        /// Включается при низкой температуре (< 15°C)
        /// </summary>
        public bool Heater { get; set; }          // Обогреватель  
        
        /// <summary>
        /// Система вентиляции (проветривания)
        /// - true: вентиляция включена, воздух обновляется
        /// - false: вентиляция выключена
        /// Включается при высокой температуре (> 25°C) или высоком уровне CO₂ (> 1200 ppm)
        /// </summary>
        public bool Ventilation { get; set; }     // Вентиляция
        
        /// <summary>
        /// Система искусственного освещения
        /// - true: освещение включено
        /// - false: освещение выключено
        /// Включается при недостаточной естественной освещенности (< 3000 lux)
        /// </summary>
        public bool Lights { get; set; }          // Освещение
        
        /// <summary>
        /// Система защиты от избыточного солнечного света (шторки, жалюзи)
        /// - true: защита активна, интенсивность света снижается
        /// - false: защита не активна
        /// Включается при избыточной освещенности для предотвращения перегрева
        /// </summary>
        public bool SunProtection { get; set; }   // Защита от солнца
    }
}
